  <h2 class="text-lg font-semibold text-zinc-100">Welche Daten gespeichert werden</h2>
  <ul class="list-disc space-y-1 pl-5">
    <li>Von Discord bei der Anmeldung: Discord-ID, Anzeigename und Avatar sowie dein Nickname auf dem Discord-Server deiner Orga (nur wenn du dort einen gesetzt hast; er wird in dieser Orga statt deines Anzeigenamens gezeigt). Die E-Mail-Adresse wird nicht abgefragt und nicht gespeichert. Dein Discord-Passwort sieht und speichert diese App nie.</li>
    <li>
      Deine Orga-Mitgliedschaften. Dafür fragt die App bei Discord deine Serverliste und deine
      Rollen auf den Servern registrierter Orgas ab (Discord-Freigaben „guilds“ und
      „guilds.members.read“), beim Login und danach alle 24 Stunden. Gespeichert wird nur, in
      welchen registrierten Orgas du Mitglied bist, nicht deine vollständige Serverliste. Die
      Discord-Zugangstokens dafür liegen in der Datenbank der App.
    </li>
    <li>Dein Hangar (Schiffe, Rüstungen, Mengen, LTI-Status) und deine Errungenschaften.</li>
    <li>Dein RSI-Handle, wie ihn der RSI-Sync von deiner Pledge-Seite übernimmt.</li>
    <li>Persönliche API-Tokens, nur als Hash. Das Klartext-Token kennt nur du, direkt nach der Erzeugung.</li>
    <li>
      Eventplanung: Events deiner Orga mit Zeit, Ort, Schiffen und Besatzungsplätzen. Wirst du
      einem Platz zugeordnet oder sagst du zu oder ab, wird das mit deinem Namen für die
      Mitglieder dieser Orga gespeichert und angezeigt.
    </li>
  </ul>

  <h2 class="text-lg font-semibold text-zinc-100">Wer was sieht</h2>
  <p>
    Daten teilst du nur mit den Mitgliedern deiner eigenen Orgas. Für Hangar und
    Errungenschaften stellst du getrennt ein, ob sie nur du oder deine Orga(s) sehen
    (Einstellungen). Dein Name und Avatar sind für die Mitglieder deiner Orgas in der
    Mitgliederliste sichtbar. Mitglieder anderer Orgas und nicht angemeldete Besucher sehen
    nichts von dir.
  </p>
  <p>
    <b>Orga-Hangar und Statistik:</b> Die Mitglieder einer Orga sehen eine anonyme Übersicht aller
    Schiffe ihrer Orga (Schiffsname und Gesamtzahl) und daraus berechnete Statistiken. Deine Schiffe
    werden dort unabhängig von deiner Sichtbarkeits-Einstellung mitgezählt, aber nie mit deinem Namen
    verknüpft. Hat nur ein Mitglied ein bestimmtes Schiff, lässt sich daraus allerdings schließen,
    dass es jemand aus der Orga besitzt.
  </p>

  <h2 class="text-lg font-semibold text-zinc-100">RSI-Sync</h2>
  <p>
    Die App selbst greift nie auf deinen RSI-Account zu. Ein Lesezeichen, das du selbst
    auf deiner RSI-Pledge-Seite anklickst, liest die Seite in deinem Browser aus, während du
    auf RSI angemeldet bist, und übergibt die Liste an ein Fenster der App. Übernommen wird
    erst nach deiner Bestätigung. Es werden nur Schiffs- und Rüstungsnamen, LTI und ggf. dein
    RSI-Handle ausgewertet; Gutscheincodes entfernt das Lesezeichen vorher.
  </p>

  <h2 class="text-lg font-semibold text-zinc-100">Externe Datenquellen</h2>
  <p>
    Der Schiffskatalog stammt aus der öffentlichen Ship Matrix von Roberts Space Industries,
    ergänzt um Angaben von FleetYards sowie Rüstungsdaten und Beschreibungen aus der
    Star Citizen Wiki. Die Abrufe laufen auf dem Server der App und enthalten keine
    Nutzerdaten. Schiffsbilder werden beim ersten Aufruf von Roberts Space Industries geladen und
    auf dem Server zwischengespeichert.
  </p>

  <h2 class="text-lg font-semibold text-zinc-100">Löschung</h2>
  <p>In den Einstellungen kannst du dein Konto samt aller Daten jederzeit unwiderruflich löschen. Verlässt du den Discord-Server deiner Orga oder verlierst die Rolle, die den Zugang erlaubt, wird dein Konto samt Hangar beim nächsten Abgleich der Mitgliederliste (spätestens nach einer Stunde) automatisch gelöscht.</p>

