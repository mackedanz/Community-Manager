<details class="text-xs text-zinc-400">
  <summary class="cursor-pointer text-zinc-300">Wie finde ich die Rollen-ID?</summary>
  <ol class="mt-2 list-decimal space-y-1 pl-5">
    <li>In Discord: Benutzereinstellungen → Erweitert → <b>Entwicklermodus</b> einschalten.</li>
    <li>Servereinstellungen → Rollen öffnen.</li>
    <li>Rechtsklick auf eine Rolle, die Orga-Mitglieder haben (z. B. „Mitglied“) → <b>Rollen-ID kopieren</b>.</li>
    <li>Die Zahl in ein freies Feld einfügen. Für jede weitere Rolle ein eigenes Feld.</li>
    <li>Rechts daneben kannst du den Namen der Rolle eintragen, damit später erkennbar ist, welche Rolle zu welcher ID gehört. Der Name dient nur zur Anzeige.</li>
  </ol>
  <p class="mt-2">
    Wer <b>eine</b> der eingetragenen Rollen hat, gilt als Mitglied. Ohne Rollen-ID zählt jeder
    auf dem Discord-Server als Mitglied, auch Gäste. Server-Admins zählen immer als Mitglied.
  </p>
</details>
